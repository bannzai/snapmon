/** 照らす前に文字の揺れ (全角・半角・大文字小文字・ひらがなとカタカナ) をそろえる。 */
function normalizeForMatching(text: string): string {
  return text
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[ぁ-ゖ]/g, (character) => String.fromCharCode(character.charCodeAt(0) + 0x60));
}

/** 文章に禁止語か他社の名称が含まれていれば、見つかった語を返す。無ければ undefined。 */
export function findModerationViolation(text: string): string | undefined {
  const normalizedText = normalizeForMatching(text);
  return (
    BANNED_ENGLISH_WORDS.find((word) => new RegExp(`(^|[^a-z])${word}([^a-z]|$)`).test(normalizedText)) ??
    [...BANNED_JAPANESE_WORDS, ...COMPETITOR_NAMES].find((word) => normalizedText.includes(normalizeForMatching(word)))
  );
}
